"""
Full-Stack Scaffold Generator Engine — Phase 3.

Produces deterministic, syntactically valid, immediately runnable boilerplate
code for full-stack (React + FastAPI + PostgreSQL) and hybrid applications
BEFORE the LLM code enrichment layer runs.

Guarantee:
Every file generated by this module is 100% syntactically valid Python/TypeScript/YAML/JSON,
has zero placeholder comments ("# TODO"), supports dual database persistence
(PostgreSQL with zero-config local SQLite fallback), and boots immediately.
"""

from __future__ import annotations

import os
import re
from typing import Any, Dict, List, Optional


def _slugify(text: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9]+", "-", text.lower()).strip("-")
    return cleaned[:40] or "project"


def _pascal_case(name: str) -> str:
    parts = re.split(r"[^a-zA-Z0-9]+", name)
    return "".join(p.capitalize() for p in parts if p) or "Item"


def _snake_case(name: str) -> str:
    s = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower()
    return re.sub(r"[^a-z0-9]+", "_", s).strip("_") or "item"


