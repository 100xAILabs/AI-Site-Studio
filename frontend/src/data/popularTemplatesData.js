/**
 * Lookup a template by slug or ID with fallback
 */
export function getFallbackTemplate(slugOrId) {
  if (!slugOrId) return null;
  const normalized = String(slugOrId).toLowerCase().trim();
  return (
    POPULAR_TEMPLATES_CATALOG.find(
      (t) =>
        t.slug === normalized ||
        t.id === normalized ||
        t.title.toLowerCase().includes(normalized) ||
        normalized.includes(t.slug)
    ) || null
  );
}
